'''Functions-What it does
np.sum(array) - Add all
np.mean(arr) - Average
np.median(arr) - Median
np.std(arr) - Standard Deviation
np.min(arr) - Minimum
np.max(arr) - Maximum
np.var(arr) - Variance
np.argmin(arr) - Index of Minimum
np.argmax(arr) - Index of Maximum'''

import numpy as np
arr=np.array([10,20,30,40,50])
print(np.sum(arr))
print(np.mean(arr))
print(np.median(arr))
print(np.min(arr))
print(np.max(arr))
print(np.std(arr))
print(np.var(arr))
print(np.argmin(arr))
print(np.argmax(arr))
